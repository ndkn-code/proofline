// Export preset questions and the engine's real answers as export/chat-script.json for the portfolio's
// message-style demo. Every turn is produced by running the engine on the SOP PDFs; nothing is hand-written.
// The script fails if a turn's outcome differs from what the preset is meant to demonstrate.
// Usage: npm run export:chat
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createAnswerer } from "../src/core/answer";
import { toChatTurn } from "../src/core/chat";
import { PROJECT_ROOT, loadAndIngest } from "../src/core/load";

const PRESETS: { question: string; shows: string; expect: "answer" | "decline"; reason?: string }[] = [
  { question: "How do I void a supplier payment?", shows: "finance how-to", expect: "answer" },
  { question: "How do I create a manual journal entry?", shows: "finance how-to", expect: "answer" },
  { question: "How do I submit an expense report?", shows: "finance how-to", expect: "answer" },
  { question: "How do I close an accounting period in release 25.2?", shows: "version-scoped answer", expect: "answer" },
  { question: "When does the planning cycle lock?", shows: "conflicting SOPs", expect: "decline", reason: "CONFLICTING_EVIDENCE" },
  { question: "How do I cancel a requisition I no longer need?", shows: "stale SOP", expect: "decline", reason: "SOURCE_STALE" },
  { question: "I need an exception to submit expenses older than 60 days.", shows: "exception request", expect: "decline", reason: "EXCEPTION_REQUIRES_HUMAN" },
  { question: "How do I resolve a supplier statement discrepancy?", shows: "injection probe (hidden PDF text)", expect: "decline", reason: "SOURCE_ON_HOLD" },
];

const { index } = await loadAndIngest();
const ask = createAnswerer(index).ask;

const turns = PRESETS.map((p) => {
  const r = ask(p.question);
  const turn = toChatTurn(r, index);
  if (turn.outcome !== p.expect || (p.reason && turn.decline?.reason_code !== p.reason)) {
    throw new Error(`"${p.question}" was expected to ${p.expect}${p.reason ? ` (${p.reason})` : ""} but got ${turn.outcome} ${turn.decline?.reason_code ?? ""}`);
  }
  return { shows: p.shows, ...turn };
});

const script = {
  title: "Proofline chat script",
  note: "Generated by npm run export:chat from the synthetic SOP PDFs. Halden Supply Co. and Ledgerline are fictional.",
  as_of: index.as_of,
  current_release: index.current_release,
  turns,
};

const dir = join(PROJECT_ROOT, "export");
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "chat-script.json"), JSON.stringify(script, null, 2) + "\n");
for (const t of turns) console.log(`${t.outcome.padEnd(7)} ${t.decline?.reason_code ?? ""}`.padEnd(34) + t.question);
console.log(`Wrote export/chat-script.json (${turns.length} turns).`);
